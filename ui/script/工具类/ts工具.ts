                            function 支线对话播放函数() {

                                let 当前线 = 获取当前主线()
                                let 支线剧情 = 获取当前进入的支线剧情()
                                支线进度增加();
                                // 加强边界检查
                                if(!支线剧情 || 支线剧情.length === 0) {
                                    log.warn("支线剧情为空，返回选项界面")
                                    支线剧情结束恢复音效()
                                    重置支线状态(获取当前主线())
                                    //@ts-ignore
                                    显示选项带音效(获取当前Day的行动选项(),false,true)
                                    return
                                }
                                
                                // 检查是否播放完毕
                                if(当前线.支线剧情进度 >= 支线剧情.length) {
                                    log.info("支线剧情播放完毕")
                                    //@ts-ignore
                                    显示选项带音效(获取当前Day的行动选项(),false,true)
                                    重置支线状态(获取当前主线())
                                    支线剧情结束恢复音效()

                                    return
                                }
                                
                                // 正常播放
                                try {
                                    let 反序列化文本 = 反序列化对话(支线剧情[当前线.支线剧情进度])

                                    同步场景(反序列化文本[2])

                                    同步当前对话的名称以及立绘(反序列化文本[0])

                                    显示对话文字带音效(反序列化文本[1],反序列化文本[0])
                                    
                                    
                                } catch(e) {
                                    重置支线状态(获取当前主线())
                                    //@ts-ignore
                                    显示选项带音效(获取当前Day的行动选项(),false,true)
                                    
                                    支线剧情结束恢复音效()

                                   throw log.error("支线对话播放错误:")
                                    
                                }
                            }

